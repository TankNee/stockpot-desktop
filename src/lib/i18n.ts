export const dictionaries: Record<Lang, Dict> = { zh, en, ja };

export const languageNames: Record<Lang, string> = {
  zh: "中文",
  en: "English",
  ja: "日本語",
};

/** Locale tags drive Intl number formatting, so a Japanese user sees 1,234.5
 *  and a Chinese user sees the same separators, while dates stay local. */
export const locales: Record<Lang, string> = {
  zh: "zh-CN",
  en: "en-US",
  ja: "ja-JP",
};

export function translate(
  lang: Lang,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const dict = dictionaries[lang] ?? zh;
  let text = dict[key] ?? dictionaries.zh[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}
